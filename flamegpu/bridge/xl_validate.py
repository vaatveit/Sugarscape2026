"""The one-off check of the GPU's xl results against Python's (xl design, section 5), and its report.

Usage: python -m bridge.xl_validate [--jobs J] [--report PATH]
It needs Python's xl results in <SUGARSCAPE_ROOT>/results-xl/ (about 2-3 hours on the CPU); when they are missing or
stale it prints the commands that make them and exits 1. It runs the GPU side itself: the seatbelts-on build into
results-gpu-xl/ for the comparison, the fast build into results-gpu-xl-fast/ for the timings.
"""

import argparse
import csv
import math
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path

from bridge.gpu_run import run_experiment_gpu
from bridge.paths import EXE, FAST_EXE, PROJECT_ROOT, SUGARSCAPE_ROOT
from experiments.registry import EXPERIMENTS
from experiments.run import load_results, result_dir, results_current

Series = list[dict[str, float]]

EXPERIMENTS_XL = ("II-4", "II-4-gini", "II-6", "II-7", "II-8")
SMOKE = "II-5/m3/v10.5"  # the longest visions at xl (10-200): GPU only
FRACTIONS = (0.10, 0.25, 0.50, 1.00)
GAP_PCT = 1.0  # a gap over 1% of the metric's scale ...
T_LIMIT = 3.0  # ... and over 3 seed spreads (|Welch t|) disagrees
VERDICT_ORDER = {"disagrees": 0, "agrees": 1, "not judged": 2}


@dataclass
class Comparison:
    exp_id: str
    metric: str
    t: int
    gpu_mean: float
    py_mean: float
    gap_pct: float
    welch_t: float | None
    verdict: str


def checkpoints(steps: int) -> list[int]:
    """10%, 25%, 50% and 100% of the run's periods, rounded to whole periods."""
    return [int(steps * f + 0.5) for f in FRACTIONS]


def _values(runs: list[Series], metric: str, t: int) -> list[float]:
    """The metric at period t in every seed, leaving out seeds where it is undefined (nan)."""
    out = []
    for series in runs:
        row = next((r for r in series if r["t"] == t), None)
        if row is not None and math.isfinite(row[metric]):
            out.append(float(row[metric]))
    return out


def _welch_t(g: list[float], p: list[float]) -> float | None:
    gv = statistics.variance(g) if len(g) > 1 else 0.0
    pv = statistics.variance(p) if len(p) > 1 else 0.0
    if gv == 0 and pv == 0:
        return None
    return (statistics.fmean(g) - statistics.fmean(p)) / math.sqrt(gv / len(g) + pv / len(p))


def _verdict(scale: float, gap_pct: float, t: float | None) -> str:
    if scale == 0:
        return "not judged"
    if gap_pct > GAP_PCT and (t is None or abs(t) > T_LIMIT):
        return "disagrees"
    return "agrees"


def compare(exp_id: str, gpu: list[Series], py: list[Series], steps: int) -> list[Comparison]:
    """Every metric column both sides have (except t), at each checkpoint."""
    metrics = [m for m in py[0][0] if m != "t" and m in gpu[0][0]]
    out = []
    for metric in metrics:
        py_means = [statistics.fmean(v) for t in range(steps + 1) if (v := _values(py, metric, t))]
        scale = max((abs(m) for m in py_means), default=0.0)
        for t in checkpoints(steps):
            g, p = _values(gpu, metric, t), _values(py, metric, t)
            if not g or not p:  # undefined on one side (e.g. a seasons metric without seasons)
                out.append(Comparison(exp_id, metric, t, math.nan, math.nan, math.nan, None, "not judged"))
                continue
            gm, pm = statistics.fmean(g), statistics.fmean(p)
            gap = 100 * abs(gm - pm) / scale if scale else math.nan
            welch = _welch_t(g, p)
            out.append(Comparison(exp_id, metric, t, gm, pm, gap, welch, _verdict(scale, gap, welch)))
    return out


def _num(v: float | None) -> str:
    return "" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.6g}"


def render_report(comparisons: list[Comparison], smoke_ok: bool, timings: dict, machine: dict) -> str:
    """The validation report as Markdown: thresholds, counts, every comparison (disagreements first), timings."""
    counts = {v: sum(c.verdict == v for c in comparisons) for v in VERDICT_ORDER}
    lines = [
        "# xl Chapter II: the GPU against Python",
        "",
        "Generated by `python -m bridge.xl_validate` (xl design, section 5). Each metric is compared at 10%, 25%, 50%"
        " and 100% of the run's periods, as the GPU's seed mean against Python's.",
        "",
        f"- **Gap:** |GPU − Python| as a percentage of the metric's scale, the largest |Python mean| over the run.",
        f"- **Spread:** Welch's t over seeds.",
        f"- A comparison **disagrees** when its gap is over {GAP_PCT:g}% *and* |t| > {T_LIMIT:g} (or there is no"
        f" spread on either side). A metric whose Python scale is 0, or that is undefined on a side, is not judged.",
        "",
        f"**Counts:** {counts['disagrees']} disagree, {counts['agrees']} agree, {counts['not judged']} not judged.",
        "",
        f"**Smoke test** ({SMOKE} at xl, visions 10–200, GPU only): {'finished' if smoke_ok else 'FAILED'}.",
        "",
        "## Comparisons",
        "",
        "| Experiment | Metric | t | GPU mean | Python mean | Gap % | Welch t | Verdict |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in sorted(comparisons, key=lambda c: (VERDICT_ORDER[c.verdict], c.exp_id, c.metric, c.t)):
        lines.append(f"| {c.exp_id} | {c.metric} | {c.t} | {_num(c.gpu_mean)} | {_num(c.py_mean)} | "
                     f"{_num(c.gap_pct)} | {_num(c.welch_t)} | {c.verdict} |")
    lines += ["", "## Timing", "",
              "Mean seconds per seed. The GPU's are from the fast build, run one seed at a time; Python's were taken "
              "with the stated `--jobs`, sharing the processor.", "",
              "| Experiment | GPU setup | GPU per period | Python setup | Python per period | Python jobs |",
              "|---|---|---|---|---|---|"]
    for exp_id, t in timings.items():
        lines.append(f"| {exp_id} | {_num(t.get('gpu_setup_s'))} | {_num(t.get('gpu_period_s'))} | "
                     f"{_num(t.get('py_setup_s'))} | {_num(t.get('py_period_s'))} | {t.get('py_jobs', '')} |")
    for side, text in machine.items():
        lines += ["", f"## Machine ({side})", "", "```", text.strip(), "```"]
    return "\n".join(lines) + "\n"


def _timing_means(folder: Path) -> tuple[float, float]:
    """Mean setup seconds and mean stepping seconds per period, from a timing.csv."""
    with (folder / "timing.csv").open(newline="") as f:
        rows = list(csv.DictReader(f))
    return (statistics.fmean(float(r["setup_s"]) for r in rows),
            statistics.fmean(float(r["stepping_s"]) / float(r["periods"]) for r in rows))


def _note_value(text: str, key: str) -> str:
    return next((line.split("=", 1)[1].strip() for line in text.splitlines() if line.split("=", 1)[0].strip() == key), "")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--jobs", type=int, default=1, help="GPU seeds at once (timings always run one at a time)")
    parser.add_argument("--report", type=Path, default=PROJECT_ROOT / "docs" / "validation" / "xl-chapter2.md")
    args = parser.parse_args(argv)

    py_out = SUGARSCAPE_ROOT / "results-xl"
    missing = [i for i in EXPERIMENTS_XL if not results_current(i, py_out, xl=True)]
    if missing:
        print("Python's xl results are missing or stale. Make them first (about 2-3 hours):")
        print(f"  cd {SUGARSCAPE_ROOT}")
        for exp_id in missing:
            print(f"  python -m experiments.run {exp_id} --xl --jobs 10")
        sys.exit(1)

    gpu_out, fast_out = PROJECT_ROOT / "results-gpu-xl", PROJECT_ROOT / "results-gpu-xl-fast"
    for exp_id in EXPERIMENTS_XL:
        run_experiment_gpu(exp_id, jobs=args.jobs, out_dir=gpu_out, exe=EXE, xl=True)
        run_experiment_gpu(exp_id, jobs=1, out_dir=fast_out, exe=FAST_EXE, xl=True)
        print(f"{exp_id}: GPU done", flush=True)
    try:
        run_experiment_gpu(SMOKE, seeds=1, out_dir=gpu_out, exe=EXE, xl=True)
        smoke_ok = True
    except RuntimeError as e:
        print(f"smoke test failed: {e}")
        smoke_ok = False

    comparisons, timings = [], {}
    for exp_id in EXPERIMENTS_XL:
        comparisons += compare(exp_id, load_results(exp_id, gpu_out), load_results(exp_id, py_out),
                               EXPERIMENTS[exp_id].steps)
        gpu_setup, gpu_period = _timing_means(result_dir(exp_id, fast_out))
        py_setup, py_period = _timing_means(result_dir(exp_id, py_out))
        py_note = (result_dir(exp_id, py_out) / "machine.txt").read_text(encoding="utf-8")
        timings[exp_id] = {"gpu_setup_s": gpu_setup, "gpu_period_s": gpu_period, "py_setup_s": py_setup,
                           "py_period_s": py_period, "py_jobs": _note_value(py_note, "jobs")}
    first = EXPERIMENTS_XL[0]
    machine = {"GPU": (result_dir(first, fast_out) / "machine.txt").read_text(encoding="utf-8"),
               "Python": (result_dir(first, py_out) / "machine.txt").read_text(encoding="utf-8")}
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(render_report(comparisons, smoke_ok, timings, machine), encoding="utf-8")
    counts = {v: sum(c.verdict == v for c in comparisons) for v in VERDICT_ORDER}
    print(f"{args.report}: {counts['disagrees']} disagree, {counts['agrees']} agree, {counts['not judged']} not judged")


if __name__ == "__main__":
    main()
