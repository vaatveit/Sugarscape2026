"""Write every sugarscape experiment of the Python registry to julia/registry.toml for the Julia port.

Usage (from julia/): python -m bridge.export_registry
Python stays the single source of truth (design: "Configuration and the registry"); a test fails when the file is out
of date. Each experiment carries its Config, its xl Config, and both fingerprints as the Python runner writes them.
"""

import math
from dataclasses import fields

from bridge.paths import JULIA_DIR
from experiments.registry import EXPERIMENTS
from experiments.run import fingerprint
from sugarscape.config import Config
from sugarscape.xl import to_xl

OUT = JULIA_DIR / "registry.toml"
# Config fields declared float (or holding floats) that the registry may spell as ints, e.g. combat_alpha=2: the
# positions within a tuple, or None for a scalar.
FLOATS = {"growback_rate": None, "combat_alpha": None, "fertility_threshold": None, "child_share": None,
          "disease_fee": None, "pollution": (0, 1), "credit": (1,)}
_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


def _string(s: str) -> str:
    return '"' + "".join(_ESCAPES.get(c, c) for c in s) + '"'


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return ("inf" if v > 0 else "-inf") if math.isinf(v) else ("nan" if math.isnan(v) else repr(v))
    if isinstance(v, str):
        return _string(v)
    if isinstance(v, tuple):
        return "[" + ", ".join(_value(x) for x in v) + "]"
    raise TypeError(f"cannot write {v!r} to TOML")


def _floated(name: str, v):
    if name not in FLOATS or v is None:
        return v
    where = FLOATS[name]
    if where is None:
        return float(v)
    return tuple(float(x) if i in where else x for i, x in enumerate(v))


def _config_lines(table: str, cfg: Config) -> list[str]:
    lines = [f"[{table}]"]
    for f in fields(cfg):
        v = _floated(f.name, getattr(cfg, f.name))
        if v is not None:
            lines.append(f"{f.name} = {_value(v)}")
    return lines


def export_text() -> str:
    out = ["# Generated by `python -m bridge.export_registry` from experiments/registry.py. Do not edit.", ""]
    for exp_id, exp in EXPERIMENTS.items():
        if not isinstance(exp.config, Config):
            continue
        out += ["[[experiment]]", f"id = {_string(exp_id)}", f"title = {_string(exp.title)}",
                f"rules = {_string(exp.rules)}", f"steps = {exp.steps}", f"seeds = {exp.seeds}",
                f"fingerprint = {_string(fingerprint(exp_id))}",
                f"xl_fingerprint = {_string(fingerprint(exp_id, xl=True))}"]
        out += _config_lines("experiment.config", exp.config)
        out += _config_lines("experiment.xl_config", to_xl(exp.config))
        out.append("")
    return "\n".join(out)


def main() -> None:
    OUT.write_text(export_text(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
